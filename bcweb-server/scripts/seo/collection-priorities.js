/*
=======================================================================================================================================
Script: scripts/seo/collection-priorities.js   (SEO priority list A — COLLECTIONS, the traffic play — READ ONLY except --review)
=======================================================================================================================================
Purpose: Collections ranked by browse demand NOT captured: gain = the extra clicks / 28d if the page earned TARGET_CTR on the
         impressions it already gets. NOT revenue-weighted on purpose — the owner decides whether a collection is worth working (a
         high-traffic low-margin one like mens-goor stays on the list; that is a judgement call, not the report's).

         Flags:  IMPROVE = 200+ impressions, CTR under target      STUCK = 4+ products but under 50 impressions (invisible)

Review cooldown: mark a collection worked / dismissed and it drops off for a period. State: docs/seo/collections-reviews.json (in
                 git). The list is also written to docs/seo/collection-priorities.md.

Moved from C:\scripts\seo\collection_priorities.py (2026-11-07). Same rules.

Usage:
    node scripts/seo/collection-priorities.js                                    (list, hides reviewed; writes the .md)
    node scripts/seo/collection-priorities.js --all                              (include reviewed)
    node scripts/seo/collection-priorities.js --review mens-goor --days 90 --note "low margin"
=======================================================================================================================================
*/

require('dotenv').config({ path: require('path').join(__dirname, '..', '..', '.env') });
const fs = require('fs');
const path = require('path');
const { parseArgs } = require('util');
const { gscQuery, gscEnd, addDays, ymd } = require('../../utils/searchConsole');
const { handleOf, shopifyCollections, loadReviews, saveReviews, SEO_DOCS, num, L, R } = require('../../utils/seo');

const TARGET_CTR = 0.02;
const REVIEWS = 'collections';
const MD_FILE = path.join(SEO_DOCS, 'collection-priorities.md');

async function main() {
  const { values: args } = parseArgs({
    options: {
      all: { type: 'boolean', default: false }, review: { type: 'string' },
      days: { type: 'string', default: '90' }, note: { type: 'string', default: '' },
    },
  });
  const today = ymd(new Date());
  const reviews = loadReviews(REVIEWS);

  if (args.review) {
    const until = ymd(addDays(new Date(), Number(args.days) || 90));
    reviews[args.review.toLowerCase()] = { reviewed: today, until, note: args.note };
    saveReviews(REVIEWS, reviews);
    console.log(`Marked '${args.review}' reviewed — hidden until ${until}. Note: ${args.note || '-'}`);
    return;
  }

  const end = gscEnd();
  const gsc = new Map();
  for (const r of await gscQuery({ start: addDays(end, -27), end, dimensions: ['page'] })) {
    const h = handleOf(r.keys[0], 'collections');
    if (!h) continue;
    const g = gsc.get(h) || { i: 0, c: 0, pw: 0 };
    g.i += r.impressions; g.c += r.clicks; g.pw += r.position * r.impressions;
    gsc.set(h, g);
  }

  const rows = [];
  for (const c of await shopifyCollections()) {
    const g = gsc.get(c.handle) || { i: 0, c: 0, pw: 0 };
    const ctr = g.i ? g.c / g.i : 0;
    const gain = g.i * Math.max(0, TARGET_CTR - ctr);
    let flag = 'ok';
    if (g.i >= 200 && ctr < TARGET_CTR) flag = 'IMPROVE';
    else if (c.products >= 4 && g.i < 50) flag = 'STUCK';
    if (flag === 'ok' && g.i < 200) continue;
    rows.push({ handle: c.handle, products: c.products, words: c.words, impr: g.i, pos: g.i ? g.pw / g.i : 0, ctr, gain, flag });
  }
  rows.sort((a, b) => b.gain - a.gain);

  const shown = []; let snoozed = 0;
  for (const r of rows) {
    const rv = reviews[r.handle];
    if (rv && rv.until > today && !args.all) { snoozed++; continue; }
    shown.push({ r, rv });
  }

  console.log(`\nCOLLECTION PRIORITIES — browse demand not captured (GSC 28d to ${ymd(end)})\n`);
  console.log(`  ${L('collection', 38)} ${R('prod', 4)} ${R('words', 5)} ${R('impr', 6)} ${R('pos', 5)} ${R('CTR', 6)} ${R('gain', 5)}  ${L('flag', 7)} reviewed`);
  console.log(`  ${'-'.repeat(98)}`);
  const md = [`# Collection priorities — ${today}`, '', `Generated by \`node scripts/seo/collection-priorities.js\`. Ranked by browse demand not captured (gain = extra clicks/28d at ${TARGET_CTR * 100}% CTR).`, '',
    '| collection | prod | words | impr | pos | CTR | gain | flag | reviewed |', '|---|--:|--:|--:|--:|--:|--:|---|---|'];
  for (const { r, rv } of shown.slice(0, 30)) {
    const rvs = rv ? `til ${rv.until}${rv.note ? ` (${rv.note})` : ''}` : '-';
    console.log(`  ${L(r.handle, 38)} ${R(r.products, 4)} ${R(r.words, 5)} ${R(num(r.impr), 6)} ${R(r.pos.toFixed(1), 5)} ${R(`${(r.ctr * 100).toFixed(1)}%`, 6)} `
      + `${R(num(r.gain), 5)}  ${L(r.flag, 7)} ${rvs}`);
    md.push(`| ${r.handle} | ${r.products} | ${r.words} | ${num(r.impr)} | ${r.pos.toFixed(1)} | ${(r.ctr * 100).toFixed(1)}% | ${num(r.gain)} | ${r.flag} | ${rvs} |`);
  }
  fs.mkdirSync(SEO_DOCS, { recursive: true });
  fs.writeFileSync(MD_FILE, `${md.join('\n')}\n`);
  console.log(`\n  gain = extra clicks/28d at ${TARGET_CTR * 100}% CTR. ${snoozed} reviewed hidden — use --all to see. List saved to docs/seo/collection-priorities.md`);
  console.log('  Mark one done:  node scripts/seo/collection-priorities.js --review <handle> --days 90 --note "..."\n');
}

main()
  .then(() => process.exit(0))
  .catch((err) => { console.error('[seo/collection-priorities] failed:', err.message); process.exit(1); });
